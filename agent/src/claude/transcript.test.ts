// ★★ Regression guard for the bug where "done" / "awaiting approval" vanished after 3 minutes (actually shipped on 2026-08-11).
//
//   Record order in the measured file:
//     12:40:00  assistant                                  ← end of the conversation
//     12:40:29  Stop hook (recorded in hookState)
//     12:40:30  system/stop_hook_summary, turn_duration     ← 0.5s later
//     12:43:36  system/away_summary                         ← ★3 minutes later
//
//   If lastActivity includes system records, once the summary is written it is judged that "there was
//   activity newer than the hook", and the list's status label disappears. **Excluding them is the requirement.**
//
// ⚠️ This used to be "tested" in status.test.ts, but the input it passed was identical to another test
//    and never went through a single line of the transcript side (= a false green). Replaced on 2026-08-13.

test('★★ derive: lastActivity is taken only from conversation records (system cleanup is not counted)', () => {
  const d = derive({
    sessionId: 's',
    headRecords: [userMsg('やあ')],
    tailRecords: [
      { type: 'assistant', timestamp: '2026-08-11T12:40:00.000Z' },
      // ↓ From here down is system cleanup. Must not be mixed into lastActivity
      { type: 'system', subtype: 'stop_hook_summary', content: 'x', timestamp: '2026-08-11T12:40:30.000Z' },
      { type: 'system', subtype: 'turn_duration', content: '12s', timestamp: '2026-08-11T12:40:30.500Z' },
      {
        type: 'system',
        subtype: 'away_summary',
        content: '離席中にテストが2件失敗しました',
        timestamp: '2026-08-11T12:43:36.000Z',
      },
    ],
  })
  // ★ Must be the time of the end of the conversation, not the away_summary 3 minutes later
  assert.equal(d.lastActivity, '2026-08-11T12:40:00.000Z')
  // ...while the summary itself is still picked up (fixing only one side is pointless)
  assert.equal(d.awaySummary, '離席中にテストが2件失敗しました')
})

test('derive: away_summary takes the last one and truncates it if long', () => {
  const d = derive({
    sessionId: 's',
    headRecords: [],
    tailRecords: [
      { type: 'system', subtype: 'away_summary', content: '古い要約' },
      { type: 'system', subtype: 'away_summary', content: 'あ'.repeat(300) },
    ],
  })
  assert.ok(d.awaySummary && d.awaySummary.length <= 161, `not truncated: ${d.awaySummary?.length}`)
  assert.ok(d.awaySummary?.startsWith('あ'))
})

