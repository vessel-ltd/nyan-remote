// ★★ How much context is currently in use (2026-08-19. Added at another session's request)
//
// ⚠️ The shape is **taken from a real transcript** (`message.usage`).
//    `input_tokens` excludes cached tokens, so in real data it was 2. The point is to add all three.

const usageRec = (u: Record<string, unknown>, type = 'assistant'): Record<string, unknown> => ({
  type,
  message: { model: 'claude-opus-5', usage: u },
})

test('★★ adds the three usage counts (dropping cached tokens changes the order of magnitude)', () => {
  // Use real values as-is
  const r = usageRec({
    input_tokens: 2,
    cache_creation_input_tokens: 1765,
    cache_read_input_tokens: 672198,
    output_tokens: 747,
  })
  assert.equal(contextTokensOf([r]), 673965)
  // ⚠️ Looking only at input_tokens gives 2 (that was the actual value)
  assert.notEqual(contextTokensOf([r]), 2)
})

test('★★ uses the last assistant (being one turn behind while responding is by design)', () => {
  const recs = [
    usageRec({ input_tokens: 10, cache_read_input_tokens: 100 }),
    { type: 'user', message: { content: 'x' } },
    usageRec({ input_tokens: 20, cache_read_input_tokens: 500 }),
    { type: 'user', message: { content: 'y' } },
  ]
  assert.equal(contextTokensOf(recs), 520)
})

test('★★ undefined when unknown (not 0 / no fail-open)', () => {
  assert.equal(contextTokensOf([]), undefined, 'empty')
  assert.equal(contextTokensOf([{ type: 'user', message: { content: 'x' } }]), undefined, 'no assistant')
  assert.equal(contextTokensOf([usageRec({})]), undefined, 'usage is empty')
  assert.equal(contextTokensOf([{ type: 'assistant', message: {} }]), undefined, 'no usage')
  assert.equal(contextTokensOf([usageRec({ input_tokens: 'x', cache_read_input_tokens: null })]), undefined, 'not a number')
  // ★ Skip broken ones and pick the usable value before them
  assert.equal(
    contextTokensOf([usageRec({ input_tokens: 5, cache_read_input_tokens: 95 }), usageRec({})]),
    100,
  )
})

test('★★ does not look past the compact boundary (it was a 15x lie on real data)', () => {
  // ⚠️ Real data (our own transcript): right after compaction the tail had only the "pre-compaction assistant",
  //    and it returned 901,602 (true value: 60,428 from the next response)
  const before = usageRec({ input_tokens: 2, cache_read_input_tokens: 901600 })
  const boundary = {
    type: 'system',
    subtype: 'compact_boundary',
    compactMetadata: { preTokens: 902839, postTokens: 14534 },
  }
  assert.equal(contextTokensOf([before, boundary]), undefined, 'returns the pre-compaction value')
  // ⚠️ Must not show postTokens (14,534) instead either (a different metric)
  assert.notEqual(contextTokensOf([before, boundary]), 14534)
  // ★ If there is a response after compaction, pick that up
  const after = usageRec({ input_tokens: 2, cache_read_input_tokens: 60426 })
  assert.equal(contextTokensOf([before, boundary, after]), 60428)
})

test('★★ values only in `iterations` (2 cases in real data / CLI 2.1.215)', () => {
  const r = usageRec({
    input_tokens: 0,
    cache_creation_input_tokens: 0,
    cache_read_input_tokens: 0,
    iterations: [
      {
        type: 'message',
        input_tokens: 2,
        cache_creation_input_tokens: 10309,
        cache_read_input_tokens: 435320,
      },
    ],
  })
  assert.equal(contextTokensOf([r]), 445631)
  // ⚠️ Do not sum them all. The **last message** is closest to "the current input"
  const multi = usageRec({
    input_tokens: 0,
    iterations: [
      { type: 'message', input_tokens: 1, cache_read_input_tokens: 99 },
      { type: 'message', input_tokens: 2, cache_read_input_tokens: 998 },
    ],
  })
  assert.equal(contextTokensOf([multi]), 1000)
  // Only message entries are used
  const other = usageRec({ input_tokens: 0, iterations: [{ type: 'tool', input_tokens: 5 }] })
  assert.equal(contextTokensOf([other]), undefined)
})

test('★★ subagent (sidechain) usage does not pollute the main number', () => {
  // ⚠️⚠️ The earlier test passed `type: 'user'`, so it **only re-checked the type check**
  //    (2026-08-19 `/code-review`, medium #2. A "false green").
  //    **Sidechain records also have `type` `assistant`**, so pass that shape
  const sub = { ...usageRec({ input_tokens: 1, cache_read_input_tokens: 9 }), isSidechain: true }
  assert.equal(contextTokensOf([sub]), undefined, 'picks up the subagent consumption')
  // ★ Even when mixed in, the main value is picked up correctly
  const main = usageRec({ input_tokens: 2, cache_read_input_tokens: 998 })
  assert.equal(contextTokensOf([main, sub]), 1000)
  // Keep the type check too, just in case
  assert.equal(contextTokensOf([usageRec({ input_tokens: 1, cache_read_input_tokens: 9 }, 'user')]), undefined)
})
